// Builds the FY25 design tokens for code from the Figma variable export.
//
// Input:  design-tokens/fy25/figma-export/{primitives,semantic,components}.json
//         (one row per Figma variable: name, type, value per mode; aliases as "{path/to/token}")
// Output: design-tokens/fy25/dist/tokens.json         W3C Design Tokens (DTCG) format
//         design-tokens/fy25/dist/tokens.css          CSS variables, light on :root, dark on [data-theme="dark"]
//         design-tokens/fy25/dist/tailwind.preset.cjs Tailwind preset that reads the CSS variables
//
// CSS variables carry their tier, because the same name can exist in two tiers
// (radius/none is both a primitive and a semantic token):
//   --ref-*  primitives   --sys-*  semantic   --comp-*  components
//
// Run with: npm run tokens
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "design-tokens", "fy25");
const TIERS = [
  { file: "primitives", key: "primitives", prefix: "ref" },
  { file: "semantic", key: "semantic", prefix: "sys" },
  { file: "components", key: "components", prefix: "comp" },
];
const tiers = TIERS.map((t) => ({ ...t, ...JSON.parse(readFileSync(join(root, "figma-export", `${t.file}.json`), "utf8")) }));

// "font-size/body 2" -> "font-size-body-2"
const slug = (path) =>
  path
    .toLowerCase()
    .replace(/[\s,/]+/g, "-")
    .replace(/[^a-z0-9-]/g, "")
    .replace(/-+/g, "-")
    .replace(/(^-|-$)/g, "");
const isAlias = (v) => typeof v === "string" && v.startsWith("{");
const aliasPath = (v) => v.slice(1, -1);

// Tokens per tier, keyed by Figma path.
const byTier = tiers.map((tier, index) => {
  const map = new Map();
  for (const [path, type, values] of tier.vars) {
    const [light, dark = light] = values;
    map.set(path, { path, type, light, dark, tier, index, multiMode: tier.modes.length > 1 });
  }
  return map;
});
const all = byTier.flatMap((m) => [...m.values()]);

// An alias points to the nearest lower tier that has that path (a semantic token aliases a primitive;
// a component token aliases a semantic token or, when there's no role for it, a primitive).
const resolve = (token, value) => {
  const path = aliasPath(value);
  for (let i = token.index - 1; i >= 0; i--) if (byTier[i].has(path)) return byTier[i].get(path);
  if (byTier[token.index].has(path) && path !== token.path) return byTier[token.index].get(path);
  return null;
};
const missing = all.flatMap((t) =>
  [t.light, t.dark].filter((v) => isAlias(v) && !resolve(t, v)).map((v) => `${t.tier.key}/${t.path} -> ${v}`)
);
if (missing.length) throw new Error(`Unresolved aliases:\n${missing.join("\n")}`);

const cssVar = (t) => `--${t.tier.prefix}-${slug(t.path)}`;
const seen = new Map();
for (const t of all) {
  const name = cssVar(t);
  if (seen.has(name)) throw new Error(`Two tokens map to ${name}: ${seen.get(name)} and ${t.path}`);
  seen.set(name, t.path);
}

const isUnitless = (t) => t.path.startsWith("font-weight/");
const dtcgType = (t) => (t.type === "COLOR" ? "color" : isUnitless(t) ? "number" : "dimension");
const raw = (t, v) => (t.type === "COLOR" || isUnitless(t) ? v : `${v}px`);

// 1. DTCG JSON: one group per tier, aliases as {tier.group.token}, the dark value in $extensions.
const dtcgValue = (t, v) => {
  if (!isAlias(v)) return raw(t, v);
  const target = resolve(t, v);
  return `{${[target.tier.key, ...target.path.split("/")].join(".")}}`;
};
const dtcg = {};
for (const t of all) {
  const parts = t.path.split("/");
  let node = (dtcg[t.tier.key] ??= {});
  for (const p of parts.slice(0, -1)) node = node[p] ??= {};
  const token = { $type: dtcgType(t), $value: dtcgValue(t, t.light) };
  if (t.multiMode && t.dark !== t.light) token.$extensions = { "com.figma": { modes: { dark: dtcgValue(t, t.dark) } } };
  const leaf = parts.at(-1);
  // A path can be a token and a group at once (color/neutral/0 and color/neutral/0/alpha-20).
  if (node[leaf]) Object.assign(node[leaf], token);
  else node[leaf] = token;
}

// 2. CSS variables. Aliases stay aliases, so changing a primitive updates everything that uses it.
const cssValue = (t, v) => (isAlias(v) ? `var(${cssVar(resolve(t, v))})` : raw(t, v));
const lightLines = [];
const darkLines = [];
for (const t of all) {
  lightLines.push(`  ${cssVar(t)}: ${cssValue(t, t.light)};`);
  if (t.multiMode && t.dark !== t.light) darkLines.push(`  ${cssVar(t)}: ${cssValue(t, t.dark)};`);
}
const css = `/* Generated by scripts/build-tokens.mjs from the FY25 Figma variables. Do not edit by hand. */
:root {
${lightLines.join("\n")}
}

[data-theme="dark"] {
${darkLines.join("\n")}
}
`;

// 3. Tailwind preset: utilities read the CSS variables, so classes follow the active mode.
const group = (tierIndex, prefix, rename = (k) => k) => {
  const out = {};
  for (const t of byTier[tierIndex].values()) {
    if (!t.path.startsWith(prefix)) continue;
    const keys = t.path.slice(prefix.length).split("/").map((k) => slug(rename(k)));
    const leaf = keys.pop();
    let node = out;
    for (const k of keys) {
      if (typeof node[k] === "string") node[k] = { DEFAULT: node[k] };
      node = node[k] ??= {};
    }
    const value = `var(${cssVar(t)})`;
    if (typeof node[leaf] === "object") node[leaf].DEFAULT = value;
    else node[leaf] = value;
  }
  return out;
};
const [REF, SYS] = [0, 1];
const theme = {
  colors: {
    // Semantic roles first: these are what components should use.
    surface: group(SYS, "surface/"),
    text: group(SYS, "text/"),
    border: group(SYS, "border/"),
    icon: group(SYS, "icon/"),
    // Primitives stay available for the rare case a role doesn't exist yet.
    ...group(REF, "color/"),
  },
  spacing: { ...group(REF, "spacing/"), ...group(SYS, "spacing/") },
  borderRadius: group(SYS, "radius/"),
  fontSize: group(REF, "font-size/", (k) => k.replace(/^text-/, "")),
  fontWeight: group(REF, "font-weight/"),
  lineHeight: group(REF, "line-height/"),
};
const preset = `// Generated by scripts/build-tokens.mjs from the FY25 Figma variables. Do not edit by hand.
// Use with: presets: [require("./design-tokens/fy25/dist/tailwind.preset.cjs")]
// and import tokens.css once. Dark mode: set data-theme="dark" on any ancestor.
module.exports = { theme: { extend: ${JSON.stringify(theme, null, 2)} } };
`;

mkdirSync(join(root, "dist"), { recursive: true });
writeFileSync(join(root, "dist", "tokens.json"), `${JSON.stringify(dtcg, null, 2)}\n`);
writeFileSync(join(root, "dist", "tokens.css"), css);
writeFileSync(join(root, "dist", "tailwind.preset.cjs"), preset);

console.log(
  `FY25 tokens: ${byTier[0].size} primitives, ${byTier[1].size} semantic, ${byTier[2].size} component. ` +
    `${lightLines.length} CSS variables, ${darkLines.length} dark overrides.`
);
